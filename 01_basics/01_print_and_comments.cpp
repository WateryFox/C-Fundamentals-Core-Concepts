#include <iostream>

int main() {
    // Single-line comment example

    /*
        Multi-line comment example:
        Demonstrating standard console output in C++
    */

    std::cout << "I like banana!" << '\n';
    std::cout << "It's very nutritious!" << '\n';

    // Basic arithmetic and variable printing logic
    int x = 5;
    int y = 6;
    int sum = x + y;

    std::cout << "x: " << x << '\n';
    std::cout << "y: " << y << '\n';
    std::cout << "Sum: " << sum << '\n';

    return 0;
}
